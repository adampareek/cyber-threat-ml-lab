from __future__ import annotations

from pathlib import Path

from cyber_threat_ml.cli import run_malware_demo, run_network_demo, run_phishing_demo


def print_metrics(title: str, metrics: dict[str, float]):
    print(f"\n=== {title} ===")
    for name, value in metrics.items():
        print(f"{name}: {value:.4f}")


def main():
    reports_dir = Path("reports")
    examples_dir = Path("examples")
    reports_dir.mkdir(exist_ok=True)
    examples_dir.mkdir(exist_ok=True)

    malware_metrics, malware_predictions = run_malware_demo()
    network_metrics, network_predictions = run_network_demo()
    phishing_metrics, phishing_predictions = run_phishing_demo()

    print_metrics("Malware File/Header Detector", malware_metrics)
    print_metrics("Network Intrusion Detector", network_metrics)
    print_metrics("Phishing URL Detector", phishing_metrics)

    phishing_predictions.head(20).to_csv(examples_dir / "sample_predictions.csv", index=False)

    report = [
        "# Model Results",
        "",
        "Generated by `python scripts/run_demo.py` using synthetic, reproducible datasets.",
        "",
        "| Detector | Accuracy | Precision | Recall | F1 | ROC AUC |",
        "|---|---:|---:|---:|---:|---:|",
    ]

    for name, metrics in [
        ("Malware file/header", malware_metrics),
        ("Network intrusion", network_metrics),
        ("Phishing URL", phishing_metrics),
    ]:
        report.append(
            f"| {name} | {metrics['accuracy']:.4f} | {metrics['precision']:.4f} | "
            f"{metrics['recall']:.4f} | {metrics['f1']:.4f} | {metrics['roc_auc']:.4f} |"
        )

    (reports_dir / "model_results.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print("\nWrote reports/model_results.md and examples/sample_predictions.csv")


if __name__ == "__main__":
    main()
